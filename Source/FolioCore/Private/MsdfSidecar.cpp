#include "FolioCore/MsdfSidecar.h"

#include <cstdlib>

namespace Folio
{
	namespace
	{
		const char* const MsdfTextureSuffix = ".msdf.png";

		std::string Trim(const std::string& Text)
		{
			std::size_t First = Text.find_first_not_of(" \t\r\n");
			if (First == std::string::npos)
			{
				return {};
			}
			const std::size_t Last = Text.find_last_not_of(" \t\r\n");
			return Text.substr(First, Last - First + 1);
		}
	}

	bool ParseMsdfSidecar(const std::string& Text, FMsdfSidecar& OutSidecar)
	{
		FMsdfSidecar Parsed;

		std::size_t Cursor = 0;
		while (Cursor <= Text.size())
		{
			std::size_t LineEnd = Text.find('\n', Cursor);
			if (LineEnd == std::string::npos)
			{
				LineEnd = Text.size();
			}

			const std::string Line = Trim(Text.substr(Cursor, LineEnd - Cursor));
			Cursor = LineEnd + 1;

			if (Line.empty() || Line[0] == '#')
			{
				continue;
			}

			const std::size_t Separator = Line.find('=');
			if (Separator == std::string::npos)
			{
				return false;
			}

			const std::string Key = Trim(Line.substr(0, Separator));
			const int Value = std::atoi(Trim(Line.substr(Separator + 1)).c_str());

			if (Key == "version")       Parsed.Version = Value;
			else if (Key == "pxem")     Parsed.Params.PxPerEm = Value;
			else if (Key == "pxrange")  Parsed.Params.PxRange = Value;
			// Unknown keys are skipped so a newer writer stays readable here.
		}

		if (!Parsed.IsValid() || Parsed.Version > MsdfSidecarVersion)
		{
			return false;
		}

		OutSidecar = Parsed;
		return true;
	}

	std::string WriteMsdfSidecar(const FMsdfSidecar& Sidecar)
	{
		return "# Generated by msdfbake. Marks the atlas beside it as a distance field.\n"
			"version=" + std::to_string(Sidecar.Version) + "\n"
			"pxem=" + std::to_string(Sidecar.Params.PxPerEm) + "\n"
			"pxrange=" + std::to_string(Sidecar.Params.PxRange) + "\n";
	}

	std::string MsdfSidecarPathFor(const std::string& TexturePath)
	{
		const std::size_t SuffixLength = std::string(MsdfTextureSuffix).size();
		if (TexturePath.size() <= SuffixLength
			|| TexturePath.compare(TexturePath.size() - SuffixLength, SuffixLength, MsdfTextureSuffix) != 0)
		{
			return {};
		}

		// Drop only the ".png", leaving the ".msdf" that names the sidecar.
		return TexturePath.substr(0, TexturePath.size() - 4);
	}
}
