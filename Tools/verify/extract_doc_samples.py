def blocks(root: pathlib.Path) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for path in sorted(root.rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        for index, match in enumerate(re.finditer(r"```cpp\n(.*?)```", text, re.S)):
            found.append((f"{path.as_posix()}#{index}", match.group(1)))
    return found


def emit(samples: list[tuple[str, str]]) -> tuple[str, int, int]:
    out = [PRELUDE]
    kept = 0
    skipped = 0

    for name, body in samples:
        if REFLECTED.search(body) or READERS_TYPE.search(body) or name in MEMBER_OF_READERS_CLASS:
            skipped += 1
            continue

        identifier = re.sub(r"\W+", "_", name).strip("_")
        indented = "\n".join(f"\t\t{line}" if line.strip() else ""
                             for line in body.strip().split("\n"))

        out.append(f"\n\t// {name}\n")
        out.append(f"\tinline void Sample_{identifier}()\n\t{{\n{indented}\n\t}}\n")
        kept += 1

    out.append(FOOTER)
    return "".join(out), kept, skipped


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--docs", default="docs")
    parser.add_argument("--out", default="Source/FolioEditor/Private/DocSamples.gen.cpp")
    parser.add_argument("--check", action="store_true",
                        help="Fail if the checked-in file is out of date rather than writing it.")
    arguments = parser.parse_args()

    text, kept, skipped = emit(blocks(pathlib.Path(arguments.docs)))
    target = pathlib.Path(arguments.out)

    if arguments.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != text:
            print(f"{target} is out of date. Run Tools/verify/extract_doc_samples.py", file=sys.stderr)
            return 1

        print(f"{kept} sample(s) up to date, {skipped} not compilable by design")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"{kept} compiled, {skipped} skipped -> {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
