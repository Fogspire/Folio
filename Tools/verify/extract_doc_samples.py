#!/usr/bin/env python3
"""Turns the C++ samples in docs/ into a translation unit, so they cannot go stale silently.

A sample naming a function that has since been renamed is worse than no sample: it is confidently
wrong, and the reader trusts it. Compiling them is the only way to know. Doing this the first time
found three - two calls missing their arguments and one whole function that did not exist.

Two kinds of block are not compiled, and both are listed explicitly rather than guessed at:

  * one declaring a `UCLASS`, which needs UnrealHeaderTool to have generated its reflection - that
    cannot happen for text lifted out of a document;
  * one that is a member of a class the reader is expected to own, like `void AEnemy::BeginPlay()`.
    A stub elaborate enough to compile that stops resembling what anyone would write.

Neither is the half that rots. A signature change breaks a *call*, and every call is compiled here.

The generated file is checked in. Re-run after editing a sample; the build fails if the sample is
wrong, and `--check` fails if the checked-in file is out of date.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

# Blocks that are a member of a class the reader owns. Listed by document and index, so nothing about
# the scaffolding leaks into the prose a reader sees.
